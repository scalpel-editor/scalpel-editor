constexpr double PointerAxisStep = 10.0;

std::string_view ComposeLocale() noexcept {
	for (const char *name : {"LC_ALL", "LC_CTYPE", "LANG"}) {
		if (const char *value = std::getenv(name); value && *value) {
			return value;
		}
	}
	return "C";
}

Scintilla::Keys KeyFromKeysym(xkb_keysym_t keysym) noexcept {
	switch (keysym) {
	case XKB_KEY_Down:
	case XKB_KEY_KP_Down:
		return Scintilla::Keys::Down;
	case XKB_KEY_Up:
	case XKB_KEY_KP_Up:
		return Scintilla::Keys::Up;
	case XKB_KEY_Left:
	case XKB_KEY_KP_Left:
		return Scintilla::Keys::Left;
	case XKB_KEY_Right:
	case XKB_KEY_KP_Right:
		return Scintilla::Keys::Right;
	case XKB_KEY_Home:
	case XKB_KEY_KP_Home:
		return Scintilla::Keys::Home;
	case XKB_KEY_End:
	case XKB_KEY_KP_End:
		return Scintilla::Keys::End;
	case XKB_KEY_Page_Up:
	case XKB_KEY_KP_Page_Up:
		return Scintilla::Keys::Prior;
	case XKB_KEY_Page_Down:
	case XKB_KEY_KP_Page_Down:
		return Scintilla::Keys::Next;
	case XKB_KEY_Delete:
	case XKB_KEY_KP_Delete:
		return Scintilla::Keys::Delete;
	case XKB_KEY_Insert:
	case XKB_KEY_KP_Insert:
		return Scintilla::Keys::Insert;
	case XKB_KEY_Escape:
		return Scintilla::Keys::Escape;
	case XKB_KEY_BackSpace:
		return Scintilla::Keys::Back;
	case XKB_KEY_Tab:
	case XKB_KEY_KP_Tab:
	case XKB_KEY_ISO_Left_Tab:
		return Scintilla::Keys::Tab;
	case XKB_KEY_Return:
	case XKB_KEY_KP_Enter:
		return Scintilla::Keys::Return;
	case XKB_KEY_KP_Add:
		return Scintilla::Keys::Add;
	case XKB_KEY_KP_Subtract:
		return Scintilla::Keys::Subtract;
	case XKB_KEY_KP_Divide:
		return Scintilla::Keys::Divide;
	default:
		break;
	}

	// Scintilla's command map uses upper-case identifiers independently of
	// the text generated by the active xkb state.
	if (keysym >= XKB_KEY_a && keysym <= XKB_KEY_z) {
		keysym += XKB_KEY_A - XKB_KEY_a;
	}
	if (keysym >= 0x20 && keysym <= 0x7e) {
		return static_cast<Scintilla::Keys>(keysym);
	}
	return static_cast<Scintilla::Keys>(0);
}

bool ModifierActive(xkb_state *state, const char *name) noexcept {
	return xkb_state_mod_name_is_active(state, name, XKB_STATE_MODS_EFFECTIVE) > 0;
}

int PointerButton(uint32_t button) noexcept {
	switch (button) {
	case BTN_LEFT:
		return 0;
	case BTN_RIGHT:
		return 1;
	case BTN_MIDDLE:
		return 2;
	default:
		return -1;
	}
}

